/* Browser contract tests use mocked HTTP responses; they do not send customer data. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '@playwright/test');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  let mode = 'failure', pending, requests = [];
  await page.route('https://oznktsrggzrzjgzzhyxv.supabase.co/functions/v1/workbook-submit', async route => {
    const body = route.request().postDataJSON(); requests.push(body);
    if (mode === 'hold') await new Promise(resolve => { pending = resolve; });
    if (mode === 'failure') return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ ok: false, error: 'unavailable' }) });
    if (mode === 'malformed') return route.fulfill({ status: 200, contentType: 'text/html', body: 'not a receipt' });
    if (mode === 'rate') return route.fulfill({ status: 429, contentType: 'application/json', body: JSON.stringify({ ok: false, error: 'rate_limited' }) });
    return route.fulfill({ status: 202, contentType: 'application/json', body: JSON.stringify({ ok: true, submission_id: body.submission_id }) });
  });
  await page.goto(`${process.env.WORKBOOK_URL || 'http://127.0.0.1:8792'}/fthb/payment.html`);
  await page.evaluate(() => document.fonts.ready);
  assert.equal(await page.locator('[data-answer]').count(), 16);
  assert.equal(await page.locator('[data-exercise]').count(), 20);
  assert.equal(await page.locator('details.drill[open]').count(), 0);
  await page.locator('#take_home_income_figure').fill('need quote');
  await page.locator('#question').fill('<img src=x onerror=alert(1)>');
  await page.locator('#exercise-1 summary').click();
  await page.locator('#exercise_01').fill('Keep these notes when I print.');
  await page.locator('#exercise-1 summary').click();
  await page.locator('#exercise-2 summary').click();
  await page.evaluate(() => { window.print = () => { window.dispatchEvent(new Event('beforeprint')); window.dispatchEvent(new Event('beforeprint')); }; });
  await page.locator('#print-workbook').click();
  assert.equal(await page.locator('#exercise-1').getAttribute('open'), '');
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('[data-print-for="take_home_income_figure"]').innerText(), 'need quote');
  assert.equal(await page.locator('[data-print-for="exercise_01"]').innerText(), 'Keep these notes when I print.');
  assert.equal(await page.locator('#send-section').isVisible(), false);
  assert.equal(await page.locator('#full_name').inputValue(), '');
  assert.equal(await page.locator('#email').inputValue(), '');
  if (process.env.SCREENSHOT_DIR) { fs.mkdirSync(process.env.SCREENSHOT_DIR, { recursive: true }); await page.pdf({ path: path.join(process.env.SCREENSHOT_DIR, 'payment-filled-print.pdf'), format: 'Letter', printBackground: true, preferCSSPageSize: true }); }
  await page.emulateMedia({ media: 'screen' });
  await page.evaluate(() => window.dispatchEvent(new Event('afterprint')));
  assert.equal(await page.locator('#exercise-1').getAttribute('open'), null);
  assert.equal(await page.locator('#exercise-2').getAttribute('open'), '');
  await page.locator('#exercise-2 summary').click();
  await page.locator('#print-workbook').click();
  await page.evaluate(() => window.dispatchEvent(new Event('afterprint')));
  assert.equal(await page.locator('details.drill[open]').count(), 0);
  await page.locator('#review-workbook').click();
  assert.equal(requests.length, 0);
  assert.equal(await page.locator('#review-panel').isVisible(), false);
  await page.locator('#full_name').fill('   '); await page.locator('#email').fill('review@example.com');
  await page.locator('#review-workbook').click(); assert.equal(await page.locator('#review-panel').isVisible(), false);
  await page.locator('#full_name').fill('Workbook Browser Test');
  await page.locator('#review-workbook').click();
  assert.equal(await page.locator('#review-panel').isVisible(), true);
  assert.equal(await page.locator('#review-content img').count(), 0);
  assert.ok((await page.locator('#review-content').innerText()).includes('<img src=x onerror=alert(1)>'));
  await page.locator('#confirm-send').click();
  await page.getByText('We couldn’t confirm', { exact: false }).waitFor();
  assert.equal(await page.locator('#take_home_income_figure').inputValue(), 'need quote');
  const firstId = requests[0].submission_id;
  mode = 'malformed'; await page.locator('#confirm-send').click();
  await page.waitForFunction(() => !document.querySelector('#confirm-send').disabled);
  assert.equal(requests[1].submission_id, firstId);
  assert.ok((await page.locator('#send-status').innerText()).includes('couldn’t confirm'));
  mode = 'rate'; await page.locator('#confirm-send').click();
  await page.getByText('There have been too many requests.', { exact: false }).waitFor();
  assert.equal(requests[2].submission_id, firstId);
  await page.locator('#edit-workbook').click();
  await page.locator('#next_decision').fill('Discuss my rough estimate.');
  await page.locator('#review-workbook').click();
  mode = 'hold'; await page.locator('#confirm-send').click();
  await page.waitForFunction(() => document.querySelector('#confirm-send').disabled);
  await page.evaluate(() => document.querySelector('#confirm-send').click());
  assert.equal(requests.length, 4); assert.notEqual(requests[3].submission_id, firstId);
  assert.equal(await page.locator('#next_decision').isDisabled(), true);
  pending();
  await page.getByText('Your workbook was received for review', { exact: false }).waitFor();
  assert.equal(await page.locator('#review-panel').isVisible(), false);
  assert.equal(await page.locator('#next_decision').inputValue(), 'Discuss my rough estimate.');
  assert.equal(await page.evaluate(() => localStorage.length), 0);
  assert.equal(await page.evaluate(() => sessionStorage.length), 0);
  assert.deepEqual(errors, []);
  await page.evaluate(() => { document.querySelectorAll('[data-exercise]').forEach(input => { input.value = '漢'.repeat(1000); input.dispatchEvent(new Event('input', { bubbles: true })); }); });
  await page.locator('#review-workbook').click();
  assert.ok((await page.locator('#send-status').innerText()).includes('too long'));
  assert.equal(requests.length, 4);
  assert.equal(await page.locator('#exercise_01').inputValue(), '漢'.repeat(1000));
  await page.evaluate(() => { document.querySelectorAll('[data-exercise]').forEach(input => { input.value = ''; input.dispatchEvent(new Event('input', { bubbles: true })); }); });
  const screenshotDir = process.env.SCREENSHOT_DIR;
  if (screenshotDir) fs.mkdirSync(screenshotDir, { recursive: true });
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    if (screenshotDir) await page.screenshot({ path: path.join(screenshotDir, `payment-${width}.png`), fullPage: true });
  }
  console.log(JSON.stringify({ pass: true, assertions: ['16 summary fields', '20 optional notes', 'identity-free populated print', 'print click and repeated events restore expanded state', 'send validation', 'text-only review', 'failure preserves answers', 'malformed success rejected', 'rate limit honest', 'retry same UUID', 'edit new UUID', 'double-submit blocked', 'receipt-only success', 'no browser persistence', 'mobile/desktop no overflow', 'no browser errors', 'UTF-8 total cap preserves oversized answers'], mockedRequests: requests.length }));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
